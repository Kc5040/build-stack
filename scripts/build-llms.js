#!/usr/bin/env node
/*
 * Validates data/tools.json, then generates:
 *   - llms.txt                  (chatbot-readable summary of the site + every tool)
 *   - assets/tools-fallback.js  (inline copy of the data so index.html works from file://)
 * Usage: node scripts/build-llms.js      (no dependencies)
 * Set SITE_URL to change the domain, e.g. SITE_URL=https://example.com node scripts/build-llms.js
 */
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const SITE_URL = (process.env.SITE_URL || "https://build-stack-beta.vercel.app").replace(/\/$/, "");
const PRICING = ["free", "freemium", "paid"];

const data = JSON.parse(fs.readFileSync(path.join(root, "data/tools.json"), "utf8"));
const errors = [];
const seen = new Set();
if (!Array.isArray(data.tools)) errors.push("tools must be an array");
(data.tools || []).forEach((t, i) => {
  const where = `tools[${i}] (${t && t.name})`;
  for (const k of ["name", "description", "category", "pricing", "url"]) {
    if (typeof t[k] !== "string" || !t[k].trim()) errors.push(`${where}: missing "${k}"`);
  }
  if (t.pricing && !PRICING.includes(t.pricing)) errors.push(`${where}: pricing must be one of ${PRICING.join("/")}`);
  if (t.url && !/^https:\/\//.test(t.url)) errors.push(`${where}: url must start with https://`);
  if (Array.isArray(data.categories) && t.category && !data.categories.includes(t.category))
    errors.push(`${where}: category "${t.category}" is not listed in "categories"`);
  const key = (t.name || "").toLowerCase();
  if (seen.has(key)) errors.push(`${where}: duplicate name`);
  seen.add(key);
});
if (errors.length) {
  console.error("tools.json has problems:\n- " + errors.join("\n- "));
  process.exit(1);
}

const tools = data.tools.slice().sort((a, b) => a.name.localeCompare(b.name));
const categories = data.categories || [...new Set(tools.map((t) => t.category))];

let out = `# Nellyon AI Stack

> Nellyon AI Stack is a curated, searchable directory of AI coding tools for vibe coders and builders: AI code editors, coding agents, code assistants, AI app builders, backends and databases, hosting and deploy platforms, and model APIs. Each listing has a one-line description, a category, a pricing model (free, freemium or paid) and a link to the official site.

Site: ${SITE_URL}/
Last updated: ${data.updated || new Date().toISOString().slice(0, 10)}
Tools listed: ${tools.length}
Machine-readable data: ${SITE_URL}/data/tools.json

Pricing labels are a quick guide. Check each tool's official site for current plans.

`;
for (const cat of categories) {
  const inCat = tools.filter((t) => t.category === cat);
  if (!inCat.length) continue;
  out += `## ${cat}\n\n`;
  for (const t of inCat) out += `- [${t.name}](${t.url}): ${t.description} Pricing: ${t.pricing}.\n`;
  out += "\n";
}
out += `## About

- [Submit a tool](${SITE_URL}/#submit): send the name, link and a one-line description.
- [Newsletter](${SITE_URL}/#newsletter): a weekly email with the best new AI dev tools.
- [Featured listings](${SITE_URL}/#sponsor): sponsored spots at the top of the directory.
`;

fs.writeFileSync(path.join(root, "llms.txt"), out);
fs.writeFileSync(
  path.join(root, "assets/tools-fallback.js"),
  "/* GENERATED by scripts/build-llms.js from data/tools.json. Do not edit by hand. */\n" +
    "window.TOOLS_FALLBACK = " + JSON.stringify(data) + ";\n"
);
console.log(`OK: ${tools.length} tools in ${categories.length} categories -> llms.txt, assets/tools-fallback.js`);
